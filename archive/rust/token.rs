#[derive(Debug, PartialEq, Clone)]
pub enum Token {
    // Core keywords
    Set,
    Task,
    Fn, // fn is alias for task
    Check,
    Loop,
    Override,
    Purge,
    Copy,
    Else,
    From,
    To,
    Times,
    True,
    False,
    Break,
    Continue,
    Const,
    As,
    // Security
    Sensitive,
    Inline,
    ConstantTime,
    // FFI / memory
    Extern,
    Alloc,
    Free,
    // Data structures
    Struct,
    Enum,
    // Error handling
    Ok,
    Err,
    Match,
    // Concurrency
    Spawn,
    Async,
    Await,
    Chan,
    // Generics
    Where,
    // Features
    Test,
    Assert,
    StaticAssert,
    Defer,
    Type,
    Int8,
    Int16,
    Int64,
    Uint8,
    Uint16,
    Uint32,
    Uint64,
    Comptime,
    Namespace,
    Use,
    In,
    Null,
    // Logical
    And,
    Or,
    Not,
    // Built-ins
    Print,
    PrintFmt,
    Return,
    Asm,
    Import,
    // Literals
    Integer(i64),
    Float(f64),
    StringLiteral(String),
    Identifier(String),
    // Arithmetic
    Plus,
    Minus,
    Star,
    Slash,
    Percent,
    // Compound assign
    PlusAssign,
    MinusAssign,
    StarAssign,
    SlashAssign,
    // Bitwise
    Pipe,
    Caret,
    Tilde,
    LessLess,
    GreaterGreater,
    // Comparison
    EqualEqual,
    NotEqual,
    Less,
    Greater,
    LessEqual,
    GreaterEqual,
    // Assignment
    Assign,
    Ampersand,
    Bang,
    // Special
    DotDot,
    DotDotEq,
    Pipe2,
    Question,
    // Delimiters
    LeftParen,
    RightParen,
    LeftBrace,
    RightBrace,
    LeftBracket,
    RightBracket,
    Comma,
    Dot,
    Colon,
    DoubleColon,
    Arrow,
    FatArrow,
    // Indent-based blocks (Python-style optional)
    Indent,
    Dedent,
    // Structure
    Newline,
    Eof,
}
