#!/usr/bin/env python3
"""C.29 — generalised 2,957-case differential harness.

Generates 2,957 deterministic Sovren programs across 12 shape families,
compiles EACH cold with the control compiler and the installed compiler,
compares rc + output SHA-256, then executes both outputs and compares exit
status, stdout and stderr. Refusal parity counts as a match only when both
sides refuse with the same rc and no artifact. One-char edits are included.

C.35: every invocation is a fresh process; no prefix replay, no state file,
no memoisation, no cached translation result. Deterministic seed so any
counterexample can be regenerated by case index alone.

Usage: tools/differ_gate.py [--control /path/to/old/compiler] [--cases N]
"""
import argparse, hashlib, json, os, random, subprocess, sys, tempfile
from pathlib import Path

R = Path(__file__).resolve().parents[1]
GATE = R / 'compilers/linux/compiler'
SEED = 20261108
FAMILIES = 12


def gen(i):
    """Return the source text of case i (deterministic, no external state)."""
    r = random.Random(SEED * 1000003 + i)
    fam = i % FAMILIES
    n = r.randrange(1, 7)
    v = r.randrange(0, 1000)
    lines = ['main:']
    if fam == 0:                              # straight-line arithmetic
        lines.append('    a: %d' % v)
        for k in range(n):
            lines.append('    a: a + %d' % r.randrange(1, 50))
        lines.append('    print a')
    elif fam == 1:                            # nested if
        lines.append('    a: %d' % v)
        for k in range(n):
            lines.append('    if a > %d -> a: a - 1' % r.randrange(0, 500))
        lines.append('    print a')
    elif fam == 2:                            # as long as loops
        lines.append('    i: 0')
        lines.append('    as long as i < %d' % n)
        lines.append('        i: i + 1')
        lines.append('    print i')
    elif fam == 3:                            # pack-mark sugar
        lines.append('    a: %d ;; b: %d' % (v, v + 1))
        lines.append('    c: a + b ;; print c')
    elif fam == 4:                            # arrow one-liners
        lines.append('    a: %d' % v)
        lines.append('    if a > 0 -> print a')
        lines.append('    if not -> print 0 - 1')
    elif fam == 5:                            # calls / forward refs
        for k in range(n):
            lines.append('    r: f%d()' % k)
        lines.append('    print r')
        lines.append('    return 0')
        for k in range(n):
            lines += ['f%d:' % k, '    return %d' % (v + k)]
    elif fam == 6:                            # strings and quotes
        lines.append("    print 'case%d:%d'" % (i, v))
        lines.append('    print "a: b"')
    elif fam == 7:                            # comments / blank lines
        lines.append('    # case %d value %d' % (i, v))
        lines.append('')
        lines.append('    a: %d' % v)
        lines.append('    # trailing: comment')
        lines.append('    print a')
    elif fam == 8:                            # long identifiers
        name = 'variable_with_a_long_name_%d_%d' % (i, v)
        lines.append('    %s: %d' % (name, v))
        lines.append('    print %s' % name)
    elif fam == 9:                            # run / times forms
        lines.append('    x: 0 %d times' % (n + 1))
        lines.append('    print x')
    elif fam == 10:                           # expression-heavy
        lines.append('    a: %d' % v)
        lines.append('    b: 1 + 2 * 3 - 4')
        lines.append('    print a + b * %d' % r.randrange(1, 9))
    else:                                     # one-char edits / tiny
        lines.append('    print %d' % v)
    if fam not in (5,):
        lines.append('    return 0')
    return '\n'.join(lines) + '\n'


def compile_one(exe, src, out):
    p = subprocess.run([exe, str(src), '-o', str(out)], cwd=R,
                       capture_output=True, timeout=60)
    data = out.read_bytes() if out.is_file() else b''
    return dict(rc=p.returncode, size=len(data),
                sha=hashlib.sha256(data).hexdigest() if data else None)


def execute(binary):
    try:
        p = subprocess.run([str(binary)], capture_output=True, timeout=15)
        return (p.returncode, p.stdout, p.stderr)
    except (subprocess.TimeoutExpired, OSError) as e:
        return ('TIMEOUT/' + type(e).__name__, b'', b'')


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--control', default='/tmp/cc_control_c5')
    ap.add_argument('--candidate', default=str(GATE))
    ap.add_argument('--cases', type=int, default=2957)
    ap.add_argument('--output', default='/home/user/evidence/C29_differ_2957.json')
    a = ap.parse_args()
    assert Path(a.control).is_file(), 'control compiler missing: ' + a.control
    bad, total = [], a.cases
    with tempfile.TemporaryDirectory(prefix='c29-differ-') as td:
        W = Path(td)
        for i in range(total):
            src = W / 'c.sov'
            src.write_text(gen(i))
            oa, ob = W / 'a.bin', W / 'b.bin'
            for p in (oa, ob):
                if p.exists():
                    p.unlink()
            ra = compile_one(a.control, src, oa)
            rb = compile_one(a.candidate, src, ob)
            ok = ra == rb
            if ok and ra['rc'] == 0 and ra['size'] > 0:
                oa.chmod(0o755); ob.chmod(0o755)
                ok = execute(oa) == execute(ob)
            if not ok:
                bad.append(dict(case=i, family=i % FAMILIES,
                                source=src.read_text(), control=ra, candidate=rb))
    report = dict(cases=total, seed=SEED, families=FAMILIES,
                  control=a.control, candidate=a.candidate,
                  mismatches=len(bad), examples=bad[:10])
    Path(a.output).parent.mkdir(parents=True, exist_ok=True)
    Path(a.output).write_text(json.dumps(report, indent=2) + '\n')
    print('C.29 differ: %d/%d cases identical (rc + SHA-256 + executed semantics)'
          % (total - len(bad), total))
    for b in bad[:5]:
        print('  counterexample case', b['case'], 'family', b['family'],
              b['control'], b['candidate'])
    return 0 if not bad else 1


if __name__ == '__main__':
    sys.exit(main())
